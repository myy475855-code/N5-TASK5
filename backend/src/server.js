import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import './db.js';
import authRoutes from './routes.js';
const app=express();
app.use(cors({origin:process.env.CLIENT_URL||'http://localhost:5173',credentials:true}));
app.use(express.json({limit:'100kb'}));app.use(cookieParser());
app.get('/api/health',(_,res)=>res.json({success:true,data:{status:'ok'}}));
app.use('/api/auth',authRoutes);
app.use((err,req,res,next)=>{console.error(err.message);res.status(500).json({success:false,error:{code:'INTERNAL_ERROR',message:'An unexpected server error occurred'}})});
const port=process.env.PORT||5000;if(process.env.NODE_ENV!=='test')app.listen(port,()=>console.log(`TalentBridge API running on http://localhost:${port}`));
export default app;
